import sys
import threading
import time
import asyncio


def _runtime_ready(app):
    try:
        tg = getattr(app, 'tg_app', None)
        handlers = getattr(tg, 'handlers', {}) if tg is not None else {}
        return bool(getattr(app, 'BOT_LOOP', None)) and bool(handlers)
    except Exception:
        return False


def _install_own_brain_247_standalone(app):
    """Start/retry Own Brain without making Telegram a dependency."""
    try:
        task = getattr(app, '_candice_own_brain_247_task', None)
        if task is not None:
            return True
        from candice_own_brain_247 import install as install_own_brain_247
        install_own_brain_247(app)
        task = getattr(app, '_candice_own_brain_247_task', None)
        if task is not None:
            print('CANDICE OWN BRAIN 24/7 STANDALONE — TELEGRAM START NOT REQUIRED')
            return True
        return False
    except Exception as exc:
        print('CANDICE OWN BRAIN 24/7 STANDALONE FAILED', repr(exc))
        return False


def _notify_strategy_start(app):
    """Send a non-trading startup status to every authorized Telegram user."""
    try:
        tg = getattr(app, 'tg_app', None)
        loop = getattr(app, 'BOT_LOOP', None)
        users = list(getattr(app, 'users', set()) or set())
        if tg is None or loop is None or not users:
            print('CANDICE STRATEGY START TELEGRAM SKIPPED — Telegram runtime/users not ready')
            return
        try:
            from candice_memory import learning_context
            ctx = learning_context(None) or {}
            overall = ctx.get('overall', {}) or {}
            samples = int(overall.get('samples', 0) or 0)
        except Exception:
            samples = 0
        text = (
            '━━━━━━━━━━━━━━━━━━━━\n🎯 CANDICE AI • SYSTEM\n━━━━━━━━━━━━━━━━━━━━\n'
            '🧠 OWN BRAIN V4 • STARTED\n━━━━━━━━━━━━━━━━━━━━\n\n'
            '✅ Strategy engine: ACTIVE\n🧠 Own Brain: V4\n📚 Memory: CONNECTED\n'
            f'📊 Learning samples: {samples}\n🛡️ V2 safety foundation: ACTIVE\n'
            '🎯 Historical edge gate: ACTIVE\n⏱️ 1M analysis: ACTIVE\n🔔 5M checkpoint: ACTIVE\n'
            '🤖 AI review: ACTIVE\n\n🚫 Auto-trade: OFF\n🚫 Martingale: OFF\n🧪 DEMO / MANUAL ONLY\n\n'
            'ℹ️ No signal was generated by this startup notice.\n'
            'Candice will alert only after all safety checks pass.'
        )
        async def _send_all():
            for cid in users:
                try:
                    m = await tg.bot.send_message(chat_id=cid, text=text, disable_web_page_preview=True)
                    print(f'CANDICE STRATEGY START TELEGRAM SENT chat={cid} message_id={m.message_id}')
                except Exception as exc:
                    print(f'CANDICE STRATEGY START TELEGRAM FAILED chat={cid}: {exc!r}')
        asyncio.run_coroutine_threadsafe(_send_all(), loop)
    except Exception as exc:
        print('CANDICE STRATEGY START TELEGRAM ERROR', repr(exc))


