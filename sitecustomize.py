def _load_runtime():
    app = None
    for _ in range(600):
        app = sys.modules.get('app') or sys.modules.get('__main__')
        if app is not None and hasattr(app, 'scan_once'):
            if _install_own_brain_247_standalone(app):
                break
        time.sleep(0.1)
    else:
        print('CANDICE OWN BRAIN 24/7 STANDALONE FAILED: app runtime not ready')
        return

    for _ in range(600):
        app = sys.modules.get('app') or sys.modules.get('__main__')
        if app is not None and hasattr(app, 'scan_once') and _runtime_ready(app):
            _install_layers(app)
            break
        time.sleep(0.1)
    else:
        print('CANDICE TELEGRAM OPTIONAL — handlers not ready; 24/7 Own Brain remains running')
        return

    for _ in range(120):
        time.sleep(0.5)
        try:
            app = sys.modules.get('app') or sys.modules.get('__main__')
            if app is None or not _runtime_ready(app):
                continue
            if not getattr(app, '_candice_ready_timer_v13', False):
                print('CANDICE READY TIMER WATCHDOG: installing missing V13 layer')
                from candice_ready_timer import install as install_ready_timer
                install_ready_timer(app)
        except Exception as exc:
            print('CANDICE READY TIMER WATCHDOG FAILED', repr(exc))


threading.Thread(target=_load_runtime, daemon=True).start()
